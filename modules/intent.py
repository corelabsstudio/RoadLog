# -*- coding: utf-8 -*-
"""손님이 쓴 말이 **봐 달라는 것인지, 그냥 건네는 말인지** 가른다 (2026-09-11 온해님 3단계).

> 단순 인사이거나 일상 대화일 때는 등불을 차감하지 않고, 사주/관상/운세/진단과
> 관련된 질문일 때만 30등불을 차감하도록

「안녕하세요」에 등불 30개를 받으면 손님은 두 번째 말을 안 건다. 그러면 대화가
아니라 자판기가 된다. 반대로 다 공짜로 열면 등불이 팔릴 이유가 없다.

가르는 순서는 셋이다. **위에서 걸리면 아래로 안 내려간다.**

  1. 표에 있는 인사·감사·짧은 반응        → 그냥 하는 말 · 값 안 나감 · 부르는 값도 0원
  2. 사주·관상 낱말이 들어 있다            → 봐 달라는 말 · 등불 30개
  3. 둘 다 아니면 LLM 에게 한 글자만 묻는다 → 0.1원 안팎

🛑 **앞단에서 가르지 않는다.** 화면에서 정하면 개발자 도구로 「인사」라고 보내
   공짜로 쓸 수 있다. 서버가 정하고, 화면은 서버가 돌려준 값을 적기만 한다.

🛑 **애매하면 그냥 하는 말로 본다.** 잘못 차감하면 손님 돈이 나가고 우리가 물어야
   한다. 잘못 안 받으면 우리 원가 0.2원이 나간다. 어느 쪽이 싼지는 분명하다.
"""
from __future__ import annotations

import re
from typing import Any

# 🛑 `_P` 는 **관리자 화면에서 고친 프롬프트를 먼저 쓰는** 도우미다. 프롬프트 모듈의
#    `get()` 을 직접 부르면 고친 적이 없을 때 빈 문자열이 온다.
from modules.saju_writer import _P, _call, ready      # noqa: F401  (같은 통로를 쓴다)

TALK = "talk"        # 그냥 건네는 말 — 등불을 안 쓴다
READ = "read"        # 봐 달라는 말 — 등불 30개

# ── 1. 표에 있는 것 ────────────────────────────────────
# 🛑 **짧은 말만 여기서 거른다.** 「안녕하세요, 제 재물운 좀 봐 주세요」처럼 인사가
#    앞에 붙은 물음까지 공짜로 열면 인사를 앞에 붙이는 것이 우회로가 된다.
_HELLO = re.compile(
    r"^(?:안녕|하이|헬로|반가|ㅎㅇ|ㅎ+|ㅋ+|ㅠ+|ㅜ+|ㄳ|ㄱㅅ|굿|넵|넹|네|예|응|오케|ok|okay"
    r"|고마워|고맙|감사|잘자|잘 자|잘가|잘 가|안녕히|또 올게|또 봐|바이|bye|하이요"
    r"|누구세요|누구야|넌 누구|너 누구|너 뭐야|이름이 뭐|뭐 할 줄|뭘 할 줄|무슨 말"
    r"|테스트|test|사랑해|귀여|귀엽|예쁘|이쁘|멋있|잘생|배고|졸려|졸리|힘들|피곤|심심)",
    re.I)
_TINY = 4            # 이보다 짧으면 물음이 아니다 (「응」 「ㅇㅇ」 「?」)

# ── 2. 봐 달라는 낱말 ──────────────────────────────────
# 사주·관상·운세·진단에 걸리는 말. 하나라도 있으면 봐 달라는 것으로 본다.
#
# 🛑 **한 글자 낱말을 넣지 않는다.** 「점」을 넣었더니 「오늘 점심 뭐 먹지」가 걸렸고,
#    「입」은 「~입니다」에 다 걸린다. 여기서 못 가른 것은 LLM 이 0.1원에 가른다 —
#    표를 억지로 넓히다 엉뚱한 말에 등불을 받는 쪽이 훨씬 비싸다.
_READ_WORDS = re.compile(
    r"(사주|관상|운세|일진|팔자|궁합|신점|점집|풀이|해석|봐\s*줘|봐\s*주|보여\s*줘|알려\s*줘"
    r"|재회|이별|헤어|연애|썸|짝사랑|고백|재물|돈복|돈\s*운|취업|이직|시험|합격|결혼|이혼|권태"
    r"|전생|수호신|대운|세운|일간|십성|오행|신살|공망|별자리"
    r"|어떨까|어떨까요|어떤가요|될까|괜찮을까|맞을까|가능할까|해도\s*될까"
    r"|얼굴|인상|이목구비|눈매|이마|성향|성격|속마음|마음)")


def by_rule(question: str) -> str | None:
    """표만 보고 가른다. 모르겠으면 None — 그때만 LLM 에게 묻는다."""
    q = " ".join(str(question or "").split())
    if not q:
        return TALK
    if len(q) <= _TINY and not _READ_WORDS.search(q):
        return TALK
    if _READ_WORDS.search(q):
        return READ
    if _HELLO.match(q) and len(q) <= 20:
        return TALK
    return None


# ── 3. 그래도 모르겠으면 물어본다 ──────────────────────
SYSTEM = """너는 손님이 쓴 한 줄을 두 갈래로만 가른다. 답은 한 낱말이다.

read = **사주 여덟 글자나 얼굴로 답할 수 있는 것.**
  · 사람과 인연 — 그 사람 마음, 재회, 이별, 결혼, 궁합, 짝사랑
  · 때 — 언제 연락할까, 언제 풀릴까, 올해는 어떤가
  · 나 — 내 성격, 내 버릇, 내 얼굴, 왜 자꾸 이러는가
  · 일과 돈 — 이직, 시험, 재물
  · 전생, 수호신, 신살

talk = **그 밖의 전부.**
  · 인사, 감사, 감탄, 사랑한다, 귀엽다
  · 너는 누구냐, 뭘 할 줄 아느냐, 그림 누가 그렸냐
  · 사이트 쓰는 법, 등불이 뭐냐, 값이 얼마냐
  · 사주와 상관없는 일상 — 점심 뭐 먹지, 날씨, 오늘 피곤하다

🛑 **애매하면 talk 이다.** 잘못 read 로 가르면 손님 돈이 나간다.
🛑 사주 글자를 짚어야 답이 되는 물음만 read 다. 그냥 궁금한 것은 talk 이다.
🛑 `read` 또는 `talk` 한 낱말만 쓴다. 설명하지 마라."""


def kind(question: str, *, model: str | None = None) -> str:
    """이 말이 봐 달라는 것인가. 못 가르면 그냥 하는 말로 본다."""
    got = by_rule(question)
    if got:
        return got
    try:
        # 🛑 **8자리로 잡으면 빈 답이 온다** (2026-09-11 실측). 답은 한 낱말인데
        #    길이에 걸려 `parts` 가 통째로 빠지고, 그러면 아래 `except` 로 떨어져
        #    **전부 그냥 하는 말**이 된다 — 돈 낼 물음까지 공짜가 됐다.
        res = _call(_P("intent", SYSTEM), str(question)[:300], model=model,
                    temperature=0.0, max_tokens=128)
        return READ if "read" in (res.get("text") or "").lower() else TALK
    except Exception:                                   # noqa: BLE001
        return TALK                                     # 🛑 막히면 안 받는다


# ── 그냥 하는 말에 답하기 ──────────────────────────────
# 🛑 **여기에 사주 풀이를 쓰지 않는다.** 「안녕」에 400자 풀이가 나오면 공짜로 다 받은
#    셈이 되고, 등불을 쓸 이유가 사라진다. 짧게 받고 무엇을 물으면 되는지 알려 준다.
SMALL_SYSTEM = """너는 {who}다. 손님이 사주·관상과 상관없는 말을 건넸다. 가볍게 받아 준다.

[말투]
- 존댓말. 「~해요」가 기본. 이름을 주면 이름+님으로 부른다.
- 위트 있게. 다만 짧다. **두 문장 안쪽·80자 안쪽.**
- 이모지·느낌표를 쓰지 않는다.

[반드시]
- 🛑 **사주나 관상 풀이를 시작하지 마라.** 여기서는 값을 받지 않는다.
- 대신 무엇을 물으면 되는지 **한 가지만** 짧게 귀띔한다.
  보기: 「궁금한 사주가 있으면 그건 제대로 봐 드릴게요」
- 🛑 「등불」이나 값 얘기를 먼저 꺼내지 마라. 화면이 따로 적어 준다."""


def small_talk(who: str, name: str, question: str, *,
               model: str | None = None) -> dict[str, Any]:
    """가볍게 한마디. 🛑 **등불을 안 쓴다** — 그래서 짧게 받는다."""
    sys_txt = _P("small", SMALL_SYSTEM).replace("{who}", who or "무냥이")
    user = "손님 이름: %s%s%s손님이 한 말: %s" % (
        name or "손님", chr(10), chr(10), str(question or "")[:300])
    return _call(sys_txt, user, model=model, max_tokens=200)


# ── 여태 물은 것을 보고 무슨 고민인지 (2026-09-11 온해님 4단계) ─────────
#
# 🛑 **여기서 상품을 고르지 않는다.** 상품 정본은 앞단 `products.js`·`gwansang.js` 다.
#    서버가 상품 목록을 또 들고 있으면 이름·값을 고칠 때마다 두 곳이 어긋난다.
#    여기서는 **주제 낱말만** 정하고, 어떤 상품이 그 주제인지는 앞단이 고른다.
#
# 🛑 **목록을 마음대로 늘리지 않는다.** 앞단 `reco.js` 의 `TOPICS` 와 같아야 한다.
#    어긋나면 골라 준 주제에 맞는 상품이 하나도 안 나온다.
TOPICS = ["재회", "이별", "속마음", "연락", "궁합", "결혼", "재물", "액운",
          "올해", "매력", "전생", "수호신", "얼굴", "첫사랑", "권태기", "밤"]

TOPIC_SYSTEM = """손님이 무냥이에게 물어 온 것들을 보고 **무슨 고민인지** 고른다.

아래 목록에서 **가장 가까운 것 하나, 많아야 둘**을 고른다. 쉼표로 나눠 쓴다.

  재회 · 이별 · 속마음 · 연락 · 궁합 · 결혼 · 재물 · 액운
  올해 · 매력 · 전생 · 수호신 · 얼굴 · 첫사랑 · 권태기 · 밤

  · 재회 = 다시 만나고 싶다 · 이별 = 끝낼까 붙잡을까
  · 속마음 = 그 사람이 나를 어떻게 보나 · 연락 = 언제 어떻게 연락하나
  · 액운 = 왜 자꾸 꼬이나 · 매력 = 나는 어떤 사람으로 보이나
  · 얼굴 = 관상으로 답할 것 · 밤 = 잠자리·몸의 결

🛑 목록에 없는 낱말을 지어내지 마라.
🛑 딱 맞는 것이 없으면 **아무것도 쓰지 마라.** 빈 줄로 답한다.
   엉뚱한 상품을 권하는 것보다 아무것도 안 권하는 편이 낫다.
🛑 낱말만 쓴다. 설명하지 마라."""


def topic(questions: list[str], *, model: str | None = None) -> list[str]:
    """여태 물어본 것들을 보고 주제를 고른다. 못 고르면 빈 목록.

    🛑 **못 고르면 아무것도 안 권한다.** 억지로 하나 붙이면 엉뚱한 상품이 나가고,
       그건 안 권하느니만 못하다.
    """
    qs = [" ".join(str(q or "").split()) for q in (questions or [])]
    qs = [q[:200] for q in qs if q][-6:]
    if not qs:
        return []
    user = "[손님이 물어본 것]" + chr(10) + chr(10).join("- " + q for q in qs)
    try:
        res = _call(_P("topic", TOPIC_SYSTEM), user, model=model,
                    temperature=0.0, max_tokens=256)
    except Exception:                                   # noqa: BLE001
        return []
    got = []
    for part in re.split(r"[\s,·]+", res.get("text") or ""):
        w = part.strip()
        if w in TOPICS and w not in got:
            got.append(w)
    return got[:2]
